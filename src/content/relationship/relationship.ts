/** One random idle tease for the current heat band. */
export function pickIdleLine(level: number, random: () => number): string {
  const bank = IDLE_TEASE_LINES[poseHeatBand(level)] ?? IDLE_TEASE_LINES[0]!;
  const index = Math.min(
    bank.length - 1,
    Math.max(0, Math.floor(random() * bank.length)),
  );
  return bank[index] as string;
}

/** Heat band of a stage: 1-4 cool, 5-7 warm, 8-10 hot. */
export function poseHeatBand(level: number): number {
  if (level <= 4) return 0;
  if (level <= 7) return 1;
  return 2;
}

